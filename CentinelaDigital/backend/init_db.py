"""Inicializa una base PostgreSQL nueva con los registros del respaldo original."""

import os

import psycopg2


def inicializar():
    database_url = os.environ.get("DATABASE_URL")
    if not database_url:
        raise RuntimeError("Falta configurar DATABASE_URL")

    with psycopg2.connect(database_url) as conexion:
        with conexion.cursor() as cursor:
            # El bloqueo evita que dos procesos inicialicen la tabla simultáneamente.
            cursor.execute("SELECT pg_advisory_xact_lock(230851947)")
            cursor.execute("SELECT to_regclass('public.reportes')")
            if cursor.fetchone()[0] is not None:
                return

            cursor.execute("""
                CREATE TABLE reportes (
                    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    tipo_registro VARCHAR(50) NOT NULL,
                    rol_usuario VARCHAR(50) NOT NULL,
                    fecha TIMESTAMP DEFAULT CURRENT_TIMESTAMP
                )
            """)
            # Estos cinco registros proceden de centinela_bd.sql, el respaldo original.
            cursor.executemany(
                "INSERT INTO reportes (id, tipo_registro, rol_usuario) VALUES (%s, %s, %s)",
                [(1, "Anonimo", "Testigo"), (2, "Registrado", "Testigo"),
                 (3, "Anonimo", "Testigo"), (7, "Registrado", "Testigo"),
                 (11, "Anonimo", "Victima")],
            )
            cursor.execute("SELECT setval(pg_get_serial_sequence('reportes', 'id'), 11)")


if __name__ == "__main__":
    inicializar()
